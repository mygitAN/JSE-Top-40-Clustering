from pathlib import Path
import json, re

root=Path.cwd(); paper=root/'paper'; results=paper/'sections/05_results.tex'
dates=['2025-06-30','2025-12-31','2026-06-30']
names=['30 June 2025','31 December 2025','30 June 2026']
keys=['clusters_tree_'+d for d in dates]
captions={key: name+r' cluster map and corresponding dendrogram for the representative seed-42 fit. All 41 instruments are included. Ticker labels, colours and member lists identify the eight Jaccard-aligned groups. The dashed line marks the eight-group cut of the average-linkage Manhattan tree fitted to these UMAP coordinates. Map units are local to this date; they do not measure movement between dates.' for key,name in zip(keys,names)}

block=r'''% BEGIN CLUSTER MAPS AND TREES
\FloatBarrier
\subsection{Cluster maps and hierarchical structure}

Figures~\ref{fig:clusters_tree_2025-06-30}--\ref{fig:clusters_tree_2026-06-30} show the fitted clusters and their corresponding dendrograms at the three decision dates. Each point in the left panel represents an instrument, with ticker labels and colours identifying its aligned group. The member list below the map defines the composition of each cluster. All 41 instruments are shown at each date, including companies that enter or leave the index during the study.

The right panel shows the full average-linkage, Manhattan-distance hierarchy fitted to the same UMAP coordinates. The dashed line identifies the cut that gives eight groups. Branch heights measure linkage distance within that representation, rather than statistical significance. Colours and aligned group identifiers are consistent with the map, the membership histories and the financial profiles in Figures~\ref{fig:profile0}--\ref{fig:profile2}. The tree cuts reproduce the saved representative partitions exactly.

These paired diagrams distinguish the location of companies in the reduced representation from the hierarchical grouping used to assign membership. The financial meaning of each group is assessed using its median feature profile. Because UMAP is fitted independently at each date, the positions and axes of separate maps should not be interpreted as a common coordinate system for temporal movement.

'''
for key in keys:
    block+='\\begin{figure}[p]\n\\centering\n\\diagram{'+key+'}\n\\caption{'+captions[key]+'}\\label{fig:'+key+'}\n\\end{figure}\n\n'
block+='\\FloatBarrier\n% END CLUSTER MAPS AND TREES\n\n'
text=results.read_text(encoding='utf-8')
if '% BEGIN CLUSTER MAPS AND TREES' in text:
    text=re.sub(r'% BEGIN CLUSTER MAPS AND TREES.*?% END CLUSTER MAPS AND TREES\s*',lambda _:block,text,flags=re.S)
else:
    marker=r'\subsection{Cluster membership over time}'
    assert text.count(marker)==1
    text=text.replace(marker,block+marker)
results.write_text(text,encoding='utf-8')

provenance_path=paper/'figure_sources.json'
provenance=json.loads(provenance_path.read_text())
old_order=[x for x in provenance['figure_order'] if x not in keys]
at=old_order.index('seed_variability')+1
provenance['figure_order']=old_order[:at]+keys+old_order[at:]
for key,date in zip(keys,dates):
    provenance['sources'][key]=f'Archived models/umap/{date}/arrays.npz; eight-group cut verified against saved labels; native TikZ generated by paper/make_cluster_tree_figures.py. See cluster_tree_sources.json.'
provenance_path.write_text(json.dumps(provenance,indent=2)+'\n',encoding='utf-8')

# Reuse the current paper captions when rebuilding the editable diagram atlas.
all_sections='\n'.join(p.read_text(encoding='utf-8') for p in (paper/'sections').glob('*.tex'))
current_captions={}
for key in provenance['figure_order']:
    match=re.search(r'\\diagram\{'+re.escape(key)+r'\}\s*\\caption\{([^\n]+)\}\\label',all_sections)
    assert match,key
    current_captions[key]=match.group(1)
atlas=r'''\input{preamble.tex}
\begin{document}
\section*{Three cross-sectional study diagram atlas}
Native TikZ and PGFPlots figures for the manuscript. The paired cluster maps and dendrograms show the actual seed-42 coordinates and full average-Manhattan hierarchies, with eight-group cuts verified against the saved study partitions.
'''
for key in provenance['figure_order']:
    atlas+='\\clearpage\n\\begin{figure}[p]\n\\centering\n\\diagram{'+key+'}\n\\caption{'+current_captions[key]+'}\\end{figure}\n'
atlas+='\\end{document}\n'
(paper/'diagrams.tex').write_text(atlas,encoding='utf-8')

appendix=paper/'sections/appendix_reproducibility.tex';text=appendix.read_text(encoding='utf-8')
text=text.replace('All fourteen diagrams','All seventeen diagrams')
addition=r'''The paired cluster maps and dendrograms use the saved seed-42 UMAP coordinates for each date. The coordinate tables and full linkage matrices are included in the LaTeX project's data folder. The average-linkage Manhattan trees were reconstructed from those coordinates, and each eight-group cut was checked against the saved partition and aligned histories with ARI equal to one. The source-array checksums, cut heights and memberships are recorded in \nolinkurl{cluster_tree_sources.json}. These figures do not rerun UMAP or change the numerical results.'''
if addition not in text:text+='\n\n'+addition+'\n'
appendix.write_text(text,encoding='utf-8')

readme=paper/'README.md';text=readme.read_text(encoding='utf-8')
text=text.replace('Fourteen editable','Seventeen editable')
addition='''
## Cluster maps beside dendrograms

The three `figures/clusters_tree_YYYY-MM-DD.tex` files show each date's UMAP
clusters beside the actual hierarchical tree. Each contains all 41 instrument
labels, consistent aligned colours, member lists and the eight-group cut.
Coordinate and full-linkage CSVs are in `data/`. `cluster_tree_sources.json`
records the checked source arrays, cut heights and memberships.

To regenerate these sources from the archived study run in this repository:

```powershell
.venv/Scripts/python.exe paper/make_cluster_tree_figures.py
.\\paper\\build.ps1 -Target Both
```

The ZIP includes the generated TikZ sources and CSVs, so normal LaTeX compilation
does not need Python, the study archive or an additional image renderer.
'''
if '## Cluster maps beside dendrograms' not in text:text+='\n'+addition
readme.write_text(text,encoding='utf-8')
assert len(provenance['figure_order'])==17
print('Integrated three paired cluster-map/dendrogram figures, updated atlas, provenance and editing guide.')
